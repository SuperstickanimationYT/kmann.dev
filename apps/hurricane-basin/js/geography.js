const GULF_STREAM = [[-80.2, 25], [-79.8, 28], [-79.5, 31], [-76.5, 34.5], [-73, 36.5], [-67, 39], [-58, 40.5], [-45, 42], [-35, 44]];

function inside(polygon, lon, lat) {
  let isInside = false;
  for (let a = 0, b = polygon.length - 1; a < polygon.length; b = a++) {
    const [xa, ya] = polygon[a];
    const [xb, yb] = polygon[b];
    if (ya > lat !== yb > lat && lon < ((xb - xa) * (lat - ya)) / (yb - ya) + xa) isInside = !isInside;
  }
  return isInside;
}

function distanceToPathKm(path, lon, lat) {
  const kmPerLon = 111 * Math.cos((lat * Math.PI) / 180);
  let nearest = Infinity;
  for (let k = 1; k < path.length; k++) {
    const [ax, ay] = [path[k - 1][0] * kmPerLon, path[k - 1][1] * 111];
    const [bx, by] = [path[k][0] * kmPerLon, path[k][1] * 111];
    const [px, py] = [lon * kmPerLon, lat * 111];
    const along = Math.max(0, Math.min(1, ((px - ax) * (bx - ax) + (py - ay) * (by - ay)) / ((bx - ax) ** 2 + (by - ay) ** 2)));
    nearest = Math.min(nearest, Math.hypot(px - ax - along * (bx - ax), py - ay - along * (by - ay)));
  }
  return nearest;
}

const smoothstep = (low, high, x) => {
  const t = Math.max(0, Math.min(1, (x - low) / (high - low)));
  return t * t * (3 - 2 * t);
};

function oceanTemperature(lon, lat) {
  const byLatitude = lat < 24 ? 28.6 + 0.4 * smoothstep(8, 18, lat) : 29 - (lat - 24) * 0.62;
  const caribbeanAndGulf = 0.7 * (1 - smoothstep(-64, -56, lon)) * (1 - smoothstep(26, 30, lat));
  const gulfStream = lat > 26 ? 3 * Math.exp(-((distanceToPathKm(GULF_STREAM, lon, lat) / 160) ** 2)) * smoothstep(26, 32, lat) : 0;
  const canaryCurrent = -2.2 * smoothstep(-32, -18, lon) * smoothstep(12, 18, lat) * (1 - smoothstep(32, 38, lat));
  return byLatitude + caribbeanAndGulf + gulfStream + canaryCurrent;
}

export function buildGeography() {
  const land = new Uint8Array(NX * NY);
  const seaTemperature = new Float64Array(NX * NY);
  for (let j = 0; j < NY; j++) {
    for (let i = 0; i < NX; i++) {
      const [lon, lat] = [lonAt(i), latAt(j)];
      const cell = j * NX + i;
      land[cell] = COASTS.some((polygon) => inside(polygon, lon, lat)) ? 1 : 0;
      seaTemperature[cell] = oceanTemperature(lon, lat);
    }
  }
  return { land, seaTemperature };
}
